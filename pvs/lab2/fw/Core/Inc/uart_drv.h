#ifndef UART_DRV_H
#define UART_DRV_H

#include <stdint.h>

#include "fifo.h"

/*
 * Общий интерфейс драйверов UART.
 *
 * Драйвер переносит байты между блоком USART и двумя очередями, которыми
 * владеет вызывающий (serial.c): принятые байты кладутся в rx, байты для
 * отправки берутся из tx. Очереди передаются драйверу при запуске, поэтому
 * при смене драйвера (переключении режима) их содержимое не теряется.
 *
 * В сборке ровно два драйвера: uart_drv_irq (по прерываниям) и uart_drv_poll
 * (по опросу, прерывания блока USART запрещены). Конфигурация "hal" собирает
 * их поверх стандартного драйвера HAL (uart_hal*.c), конфигурация "myuart" -
 * поверх собственного регистрового драйвера (myuart.c, часть 2 работы).
 * Все функции неблокирующие.
 */
typedef struct {
    /* Перевести блок USART в свой режим и начать обслуживать очереди */
    void (*start)(fifo_t *rx, fifo_t *tx);

    /* Прекратить обмен; ещё не переданные данные остаются в очереди tx */
    void (*stop)(void);

    /* В очередь tx добавлены данные: начать передачу, если она не идёт */
    void (*kick)(void);

    /* Шаг обслуживания из главного цикла (нужен только драйверу по опросу) */
    void (*poll)(void);
} uart_drv_t;

/* Однократная настройка блока USART: тактирование, выводы, кадр 8N1, скорость */
void uart_port_init(uint32_t baud);

extern const uart_drv_t uart_drv_irq;
extern const uart_drv_t uart_drv_poll;

#endif /* UART_DRV_H */
