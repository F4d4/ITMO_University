#include "stm32f4xx_hal.h"

/*
 * Системный таймер SysTick даёт миллисекундный счётчик, на котором построены
 * все выдержки времени. Обработчик прерывания блока USART находится в файле
 * выбранной реализации драйвера UART (uart_hal.c или uart_my.c). Остальные
 * векторы обслуживает обработчик по умолчанию из файла начальной загрузки.
 */
void SysTick_Handler(void)
{
    HAL_IncTick();
}
