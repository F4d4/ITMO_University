#include "stm32f4xx_hal.h"

/*
 * Единственное используемое прерывание - системный таймер SysTick.
 * Заданием запрещено применять прерывания и таймеры, кроме SysTick: он
 * обеспечивает миллисекундный счётчик, на котором построены все выдержки
 * времени. Остальные векторы обслуживает обработчик по умолчанию из файла
 * начальной загрузки.
 */
void SysTick_Handler(void)
{
    HAL_IncTick();
}
