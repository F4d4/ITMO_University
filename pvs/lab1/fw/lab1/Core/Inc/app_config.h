#ifndef APP_CONFIG_H
#define APP_CONFIG_H

/*
 * Единственное место, где заданы временные параметры приложения.
 * Обоснование значений приведено в отчёте (раздел 1).
 */

/* --- Драйвер кнопки: счётчик антидребезга с гистерезисом --- */
#define BTN_POLL_MS              1u    /* шаг счётчика */
#define BTN_CNT_MAX             25u
#define BTN_CNT_PRESS           20u    /* нажатие: 20 мс устойчивого замыкания */
#define BTN_CNT_RELEASE          5u    /* отпускание: 20 мс устойчивого размыкания */

/* --- Классификация нажатия --- */
#define MORSE_DASH_THRESHOLD_MS 300u   /* < порога - точка, >= - тире */

/* --- Конец ввода --- */
#define MORSE_INPUT_TIMEOUT_MS 2000u   /* "долгая пауза после последнего нажатия" */

/* --- Подтверждение ввода двухцветным светодиодом --- */
#define MORSE_FEEDBACK_MS       120u   /* "короткое мерцание" */

/* --- Индикация переполнения буфера --- */
#define MORSE_ERR_STEP_MS        60u
#define MORSE_ERR_CYCLES          6u

/* --- Ёмкость последовательности (по заданию - до 8 нажатий) --- */
#define MORSE_CAPACITY            8u

/*
 * Воспроизведение зелёным светодиодом.
 * T - базовая единица (точка). Канон азбуки Морзе: тире = 3T,
 * межэлементный интервал = 1T, межсловный = 7T.
 */
#define MORSE_UNIT_MS           200u
#define MORSE_DOT_UNITS           1u
#define MORSE_DASH_UNITS          3u
#define MORSE_GAP_UNITS           1u
#define MORSE_LEAD_IN_UNITS       3u   /* пауза перед началом передачи */
#define MORSE_TAIL_UNITS          7u   /* пауза после передачи */

/*
 * Политика переполнения. 0 - строго по тексту задания: ждём паузу,
 * лишние нажатия отбрасываем с индикацией ошибки.
 * 1 - автоматическая отправка по заполнении буфера.
 */
#define MORSE_AUTOSEND_ON_FULL    0

#endif /* APP_CONFIG_H */
