#ifndef FIFO_H
#define FIFO_H

#include <stdint.h>
#include <stdbool.h>

/*
 * Кольцевая очередь байтов (FIFO) фиксированной ёмкости.
 *
 * Память под элементы выделяет владелец очереди, поэтому размер каждого
 * экземпляра задаётся на этапе компиляции там, где объявлен массив. Модуль
 * ничего не знает ни о UART, ни о прикладной задаче: в программе он
 * используется и как буфер драйвера UART, и как очередь символов азбуки
 * Морзе, ожидающих проигрывания.
 *
 * Доступ из прерываний. Очередь рассчитана на одного писателя и одного
 * читателя. Индекс head меняет только писатель, tail - только читатель;
 * каждый индекс - 16-битная переменная, запись которой выполняется одной
 * командой и прерыванием разорвана быть не может. Писатель сначала кладёт
 * данные и лишь затем сдвигает head, читатель сначала забирает данные и лишь
 * затем сдвигает tail. Поэтому сторона, прервавшая другую, всегда видит
 * согласованное состояние - в худшем случае она не заметит только что
 * добавленный (или освобождённый) элемент и обработает его при следующем
 * обращении. Критическая секция при таком разделении не нужна.
 *
 * Если писателей или читателей больше одного, взаимное исключение между ними
 * обязан обеспечить вызывающий.
 *
 * Одна ячейка массива всегда остаётся свободной, чтобы различать пустую и
 * полную очередь по одним индексам: ёмкость равна размеру массива минус 1.
 */
typedef struct {
    uint8_t          *buf;
    uint16_t          size;
    volatile uint16_t head;   /* куда писать следующий байт; меняет только писатель */
    volatile uint16_t tail;   /* откуда читать следующий байт; меняет только читатель */
} fifo_t;

/* Размер массива для очереди заданной ёмкости */
#define FIFO_STORAGE_SIZE(capacity)  ((capacity) + 1u)

void     fifo_init (fifo_t *f, uint8_t *storage, uint16_t storage_size);

/* --- Сторона писателя --- */

/* false - очередь полна, байт не записан */
bool     fifo_put  (fifo_t *f, uint8_t byte);

/* Всё или ничего: false - места не хватает, очередь не изменена */
bool     fifo_write(fifo_t *f, const uint8_t *data, uint16_t len);

uint16_t fifo_free (const fifo_t *f);

/* --- Сторона читателя --- */

/* false - очередь пуста */
bool     fifo_get  (fifo_t *f, uint8_t *byte);

/*
 * Непрерывный участок ещё не прочитанных данных без извлечения из очереди:
 * возвращает его длину и адрес начала. Позволяет передать данные
 * периферийному блоку прямо из памяти очереди и освободить их вызовом
 * fifo_drop() только после того, как они действительно отправлены.
 */
uint16_t fifo_peek_linear(const fifo_t *f, const uint8_t **data);

/* Освободить n первых байтов (n не больше fifo_count) */
void     fifo_drop (fifo_t *f, uint16_t n);

/* Отбросить всё содержимое */
void     fifo_flush(fifo_t *f);

/* --- Любая сторона --- */
uint16_t fifo_count(const fifo_t *f);
uint16_t fifo_capacity(const fifo_t *f);

#endif /* FIFO_H */
