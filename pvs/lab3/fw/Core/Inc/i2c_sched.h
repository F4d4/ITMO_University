#ifndef I2C_SCHED_H
#define I2C_SCHED_H

#include <stdint.h>

/*
 * Расписание обмена по шине I2C.
 *
 * Прерывание таймера с периодом SCHED_TICK_US - один такт расписания. В
 * каждом такте запускается не больше одной транзакции: какому устройству
 * принадлежит такт, задаёт циклическая таблица. Если в такте шина ещё
 * занята предыдущей транзакцией, такт пропускается - транзакции не
 * пересекаются ни при каких задержках.
 */

typedef struct {
    uint32_t ticks;
    uint32_t busy_skips;   /* тактов, в которых шина ещё была занята */
} i2c_sched_stats_t;

extern volatile i2c_sched_stats_t i2c_sched_stats;

/* Запуск таймера расписания; к этому моменту устройства уже инициализированы */
void i2c_sched_start(void);

#endif /* I2C_SCHED_H */
