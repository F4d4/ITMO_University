#ifndef OLED_H
#define OLED_H

#include <stdbool.h>
#include <stdint.h>

#include "i2c_bus.h"

/*
 * OLED-дисплей WEO012864DL 128 x 64 (контроллер SSD1306).
 *
 * Видеопамять - 8 страниц по 128 байт; байт - столбец из восьми точек
 * страницы, младший бит сверху. Кадр в этом формате готовит модуль gfx.
 *
 * Двойная буферизация: главный цикл рисует в своём буфере и отдаёт
 * готовый кадр oled_submit(), который копирует его в буфер передачи.
 * Буфер передачи планировщик отправляет в дисплей частями в своих тактах.
 * Пока кадр передаётся, следующий не принимается.
 */

#define OLED_WIDTH       128u
#define OLED_HEIGHT       64u
#define OLED_FRAME_SIZE  (OLED_WIDTH * OLED_HEIGHT / 8u)

/* Сброс и инициализация контроллера, очистка экрана; обмен по опросу */
bool oled_init(void);

/* Можно ли сейчас отдать новый кадр */
bool oled_ready(void);

/* Принять кадр на передачу; false - предыдущий ещё передаётся */
bool oled_submit(const uint8_t *frame);

/* Очередная транзакция передачи кадра для планировщика; false - передавать нечего */
bool oled_next_txn(i2c_txn_t *t);

#endif /* OLED_H */
